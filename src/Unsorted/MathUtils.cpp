// It's a linear congruential generator called MSVCRT for Microsoft C Runtime
u32 randomInt() {
    seed = seed * 0x19660d + 0x3c6ef35f;
    return seed;
}

inline u16 lookIntoAtanTable(f32 numerator, f32 denominator) {
    return 0.0f == denominator ? 
        atanTable[0] : 
        atanTable[(int)(0.5f + (f32)(1024.0f * (numerator / denominator)))];
}

inline f32 dot(f32 ax, f32 ay, f32 az, f32 bx, f32 by, f32 bz) {
  return ax * bx + ay * by + az * bz;
}

// Returns a 16-bit binary angle. (0x10000 = 2PI rad, 0x4000 = PI/2 rad)
u16 atan2BAM(f32 firstAxis, f32 secondAxis) {
    u16 result; 

    if (secondAxis >= 0.0f) {
        if (firstAxis >= 0.0f) {
            if (firstAxis >= secondAxis) {
                result = 0 + lookIntoAtanTable(secondAxis, firstAxis);
            } else {
                result =  0x4000 - lookIntoAtanTable(firstAxis, secondAxis);
            }
        } else {
            firstAxis = -firstAxis;
            if (firstAxis < secondAxis) {
                result = lookIntoAtanTable(firstAxis, secondAxis) + 0x4000;
            } else {
                result =  0x8000 - lookIntoAtanTable(secondAxis, firstAxis);
            }
        }
    } else {
        secondAxis = - secondAxis;
        if (firstAxis < 0.0f) {
            firstAxis = -firstAxis;
            if (firstAxis >= secondAxis) {
                result = lookIntoAtanTable(secondAxis, firstAxis) + 0x8000;
            } else {
                result = 0xC000 - lookIntoAtanTable(firstAxis, secondAxis);
            }
        } else {
            if (firstAxis < secondAxis) {
                result = lookIntoAtanTable(firstAxis, secondAxis) + 0xC000;
            } else {
                result = -lookIntoAtanTable(secondAxis, firstAxis);
            }
        }
    }

    return result;
}

// Calculate the intersection of a line from the segment [ `segmentStart` , `segmentEnd` ]
// with the plane of point `pointOnPlan` and normal `normal`
// 99% match, only frame size: https://decomp.me/scratch/xPKXo
Vec lineIntersectWithPlane(Vec* segmentStart, Vec* segmendEnd, Vec* pointOnPlan, Vec* normal) {
    f32 dx = segmendEnd->x - segmentStart->x;
    f32 dy = segmendEnd->y - segmentStart->y;
    f32 dz = segmendEnd->z - segmentStart->z;

    f32 t = (normal->x * (pointOnPlan->x - segmentStart->x) +
            normal->y * (pointOnPlan->y - segmentStart->y) +
            normal->z * (pointOnPlan->z - segmentStart->z)) /
            dot(normal->x, normal->y, normal->z, dx, dy, dz);


    Vec res;
    res.x = segmentStart->x + t * dx;
    res.y = segmentStart->y + t * dy;
    res.z = segmentStart->z + t * dz;

    return res;
}

// Project `point` on the line delimited by [ `segmentStart` , `segmentEnd` ]
// Write the distance from the point to the projection into `outClosest`
// Returns -1 if the projection is before `segmentStart`, 1 is after `segmentEnd` and 0 otherwise
s32 getClosestPointOnLine(Vec* point, Vec* segmentStart, Vec* segmentEnd, f32* outDist, Vec* outClosest) {
    f32 segStartX = segmentStart->x;
    f32 segStartY = segmentStart->y;
    f32 segStartZ = segmentStart->z;

    f32 dx = segmentEnd->x - segStartX;
    f32 dy = segmentEnd->y - segStartY;
    f32 dz = segmentEnd->z - segStartZ;

    f32 t = (dx * (point->x - segStartX) + 
            dy * (point->y - segStartY) + 
            dz * (point->z - segStartZ)) / 
            (dx * dx + dy * dy + dz * dz);

    f32 r_x = segStartX + (dx * t);
    f32 r_y = segStartY + (dy * t);
    f32 r_z = segStartZ + (dz * t);
    if (outClosest != NULL) {
        outClosest->x = r_x;
        outClosest->y = r_y;
        outClosest->z = r_z;
    }

    r_x = r_x - point->x;
    r_y = r_y - point->y;
    r_z = r_z - point->z;
    *outDist = sqrtf(r_x * r_x + r_y * r_y + r_z * r_z);
    
    if (t < 0.0f) return -1;
    if (t > 1.0f) return 1;
    return 0;
}

